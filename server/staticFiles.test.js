const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const http = require('node:http')
const { serveStatic } = require('./staticFiles')

test('static assets stream ranges, revalidate, support HEAD and do not mask missing chunks', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pfc-static-'))
  fs.writeFileSync(path.join(dir, 'index.html'), '<html>app</html>')
  fs.writeFileSync(path.join(dir, 'video.mp4'), '0123456789')
  const server = http.createServer((req, res) => void serveStatic(req, res, dir, req.url).catch(() => { res.writeHead(500); res.end() }))
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  t.after(() => { server.closeAllConnections(); server.close(); fs.rmSync(dir, { recursive: true, force: true }) })
  const base = `http://127.0.0.1:${server.address().port}`
  const range = await fetch(base + '/video.mp4', { headers: { Range: 'bytes=2-5' } })
  assert.equal(range.status, 206)
  assert.equal(range.headers.get('content-range'), 'bytes 2-5/10')
  assert.equal(await range.text(), '2345')
  assert.equal((await fetch(base + '/video.mp4', { headers: { Range: 'bytes=99-' } })).status, 416)
  const head = await fetch(base + '/video.mp4', { method: 'HEAD' })
  assert.equal(head.headers.get('content-length'), '10')
  assert.equal(await head.text(), '')
  assert.equal((await fetch(base + '/video.mp4', { headers: { 'If-None-Match': head.headers.get('etag') } })).status, 304)
  assert.equal((await fetch(base + '/assets/missing.js')).status, 404)
  assert.equal(await (await fetch(base + '/dashboard')).text(), '<html>app</html>')
  assert.equal((await fetch(base + '/%zz')).status, 400)
  assert.equal((await fetch(base + '/.env')).status, 400)
})
